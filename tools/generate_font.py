"""Generate an uncompressed LVGL 8 font at a nominal size of 16 pixels.

Pillow rasterizes the bundled Montserrat font; ASCII, Latin-1 and four punctuation
glyphs are included. No Node toolchain or font loading from SD is required.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/Montserrat-Medium.ttf"


def generate(size=16, suffix="16", stroke=0, clock=False):
    name = f"pda_font_{suffix}"
    out = ROOT / f"src/ui/{name}.c"
    font = ImageFont.truetype(str(FONT), size)
    codes = sorted(set(map(ord, " +-.,:0123456789eE"))) if clock else list(range(32, 127)) + list(range(160, 256)) + [0x03c0, 0x2013, 0x2014, 0x2022, 0x20AC, 0x221a]
    bitmap = []
    descriptors = ["    {0, 0, 0, 0, 0, 0}"]
    for code in codes:
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls", stroke_width=stroke)
        width, height = right - left, bottom - top
        offset = len(bitmap)
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, anchor="ls", fill=255, stroke_width=stroke, stroke_fill=128)
            pixels = [round(p / 17) for p in image.get_flattened_data()]
            for i in range(0, len(pixels), 2):
                bitmap.append((pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0))
        descriptors.append(f"    {{{offset}, {round((font.getlength(char)+stroke)*16)}, {width}, {height}, {left}, {-bottom}}}")
    bitmap_lines = ["    " + ",".join(f"0x{x:02x}" for x in bitmap[i:i+20]) for i in range(0, len(bitmap), 20)]
    offsets = [code - codes[0] for code in codes]
    asc, desc = font.getmetrics()
    output = "/* Generated by tools/generate_font.py. Montserrat: SIL OFL 1.1. */\n#include <lvgl.h>\n\n"
    output += "static const uint8_t glyph_bitmap[] = {\n" + ",\n".join(bitmap_lines) + "\n};\n"
    output += "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n" + ",\n".join(descriptors) + "\n};\n"
    output += "static const uint16_t unicode_list[] = {" + ",".join(map(str, offsets)) + "};\n"
    output += f"""
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {codes[0]}, .range_length = {codes[-1]-codes[0]+1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(codes)},
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static lv_font_fmt_txt_glyph_cache_t cache;
static lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0, .cache = &cache
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {asc+desc+2*stroke}, .base_line = {desc+stroke},
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -1, .underline_thickness = 1,
    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL
}};
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(output)
    print(f"{out.name}: {len(codes)} glyphs, {len(bitmap)} bitmap bytes, nominal size {size} px")


if __name__ == "__main__":
    generate()
    generate(16, "16_bold", stroke=1)
    generate(28, "28")
    generate(48, "48", clock=True)
